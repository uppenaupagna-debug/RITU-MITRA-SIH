export function getLocalizedDiseaseData(best, lang) {
  if (!best) return null;
  if (!lang || lang === "en") return best;

  const dt = diseaseTranslations[best.label]?.[lang];
  const cropTrans = cropTranslations[lang]?.[best.crop] || best.crop;
  const severityTrans = severityTranslations[lang]?.[best.severity] || best.severity;

  if (!dt) {
    return {
      ...best,
      crop: cropTrans,
      severity: severityTrans,
    };
  }

  return {
    ...best,
    friendly: dt.friendly || best.friendly,
    crop: dt.crop || cropTrans || best.crop,
    severity: dt.severity || severityTrans || best.severity,
    symptoms: dt.symptoms || best.symptoms,
    suggested_actions: dt.suggested_actions || best.suggested_actions,
    cultural_remedies: dt.cultural_remedies || best.cultural_remedies,
    prevention: dt.prevention || best.prevention,
    cure: dt.cure || best.cure,
    consult_threshold: dt.consult_threshold || best.consult_threshold,
  };
}

export function getLocalizedTop3Item(item, lang) {
  if (!item) return item;
  if (!lang || lang === "en") return item;
  const dt = diseaseTranslations[item.label]?.[lang];
  return {
    ...item,
    friendly: dt?.friendly || item.friendly || item.label?.replace(/___/g, " - ").replace(/_/g, " "),
  };
}
